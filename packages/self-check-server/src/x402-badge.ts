// A badge an operator can paste on his own front door.
//
// Why this exists, and it is a position rather than a feature. The conformance
// ladder is only a unit if other people use it, and nobody adopts a unit because it
// sits in a document. A badge gets adopted because the operator wants to show the
// result, and every badge he pastes carries the measurement back to where it was
// made. That is the cheapest distribution there is, and in this corner nobody does
// it yet.
//
// THE ONE HARD DESIGN CHOICE: this never measures live. It answers from a dated,
// bundled measurement and nothing else. Two reasons, the second being the heavier:
//  - measuring on request would let anyone use this server to probe arbitrary hosts,
//    on our address and in our logs. That is someone else's rate limit to spend, not
//    ours to give away.
//  - a badge that re-measures on every page view reports a different answer on every
//    hiccup, and a number that changes by the minute is not a measurement.
//
// The price is that a badge can go STALE, and there is only one honest answer to
// that: the measurement date is IN the badge. Then an old badge is visibly old
// rather than quietly wrong, which is exactly the failure that once left a public
// page of ours asserting something untrue for weeks.
//
// SECURITY, and the simplest of the four checks is the one that matters here. The
// caller's url is NEVER written into the SVG. Only a level and a date from our own
// data are rendered, and an unknown endpoint gets a flat "not measured" without any
// echo. That removes script injection through an SVG as a category rather than
// filtering for it, which is the kind of defence that cannot be bypassed by a
// cleverer payload.

import type { Request, Response } from "express";
import { readFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

interface Meting {
  url: string;
  host: string;
  trede: number;
  editie: string;
}

interface Bundel {
  gegenereerd: string;
  aantal: number;
  metingen: Meting[];
}

let bundelCache: Bundel | null = null;

/**
 * The bundled measurements, read once.
 *
 * Generated by `x402-metingen-bundel.mjs` in the agent-receipt-verify repository and
 * committed here as data. A missing or broken file must not take the route down: it
 * means every endpoint answers "not measured", which is true and harmless, rather
 * than a 500 on a badge in someone else's README.
 */
export function leesBundel(pad?: string): Bundel {
  if (bundelCache && !pad) return bundelCache;
  const hier = dirname(fileURLToPath(import.meta.url));
  const kandidaten = pad
    ? [pad]
    : [join(hier, "..", "data", "x402-metingen.json"), join(hier, "..", "..", "data", "x402-metingen.json")];
  for (const k of kandidaten) {
    if (!existsSync(k)) continue;
    try {
      const j = JSON.parse(readFileSync(k, "utf8")) as Bundel;
      if (Array.isArray(j.metingen)) {
        if (!pad) bundelCache = j;
        return j;
      }
    } catch {
      // A corrupt bundle is the same situation as a missing one: nothing measured.
    }
  }
  const leeg: Bundel = { gegenereerd: "onbekend", aantal: 0, metingen: [] };
  if (!pad) bundelCache = leeg;
  return leeg;
}

/** Normalise for comparison only: a trailing slash must not change the answer. */
function normaliseer(url: string): string {
  try {
    const u = new URL(url);
    const pad = u.pathname.replace(/\/$/, "");
    return (u.origin + pad + u.search).toLowerCase();
  } catch {
    return url.trim().toLowerCase();
  }
}

export function zoekMeting(url: string, bundel: Bundel): Meting | null {
  const doel = normaliseer(url);
  for (const m of bundel.metingen) {
    if (normaliseer(m.url) === doel) return m;
  }
  return null;
}

const KLEUREN: Record<string, string> = {
  "L0": "#9f6000",
  "L1": "#6a7f00",
  "L2": "#2e7d32",
  "L3": "#1b5e20",
  "L4": "#1b5e20",
  "L5": "#0d3d10",
  "L-": "#8a1c1c",
  "?": "#555555",
};

/**
 * A flat SVG badge. Hand written on purpose: a badge that pulls a dependency in is a
 * dependency in everyone else's README, and the whole thing is forty lines.
 *
 * Widths are computed from the text length rather than measured, so the box can be a
 * pixel or two wide for a given font. That is the right trade here: a slightly wide
 * badge is nothing, a badge that needs a font metric library is a liability.
 */
export function maakSvg(rechts: string, kleur: string, titel: string): string {
  const links = "x402 receipt";
  const bL = 7 * links.length + 12;
  const bR = 7 * rechts.length + 14;
  const breed = bL + bR;
  // Only our own fixed strings and the computed level reach this template; nothing
  // from the request does. Still escaped, because a template that is safe only
  // because of what callers happen to pass is safe by luck.
  const esc = (s: string) =>
    s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${breed}" height="20" role="img" aria-label="${esc(links)}: ${esc(rechts)}">
<title>${esc(titel)}</title>
<linearGradient id="s" x2="0" y2="100%"><stop offset="0" stop-color="#bbb" stop-opacity=".1"/><stop offset="1" stop-opacity=".1"/></linearGradient>
<clipPath id="r"><rect width="${breed}" height="20" rx="3" fill="#fff"/></clipPath>
<g clip-path="url(#r)">
<rect width="${bL}" height="20" fill="#555"/>
<rect x="${bL}" width="${bR}" height="20" fill="${esc(kleur)}"/>
<rect width="${breed}" height="20" fill="url(#s)"/>
</g>
<g fill="#fff" text-anchor="middle" font-family="Verdana,Geneva,DejaVu Sans,sans-serif" font-size="11">
<text x="${bL / 2}" y="14">${esc(links)}</text>
<text x="${bL + bR / 2}" y="14">${esc(rechts)}</text>
</g>
</svg>`;
}

export function handleBadge(req: Request, res: Response): void {
  const url = typeof req.query.url === "string" ? req.query.url : "";
  const bundel = leesBundel();
  const m = url ? zoekMeting(url, bundel) : null;

  const label = m ? (m.trede >= 0 ? "L" + m.trede : "L-") : "?";
  const rechts = m ? `${label} · ${m.editie}` : "not measured";
  const titel = m
    ? `Level ${label} on ${m.editie}, measured by agent-receipt-verify (github.com/holistis/agent-receipt-verify). The ladder and what it deliberately does not measure are in CONFORMANCE.md.`
    : "Not measured by agent-receipt-verify (github.com/holistis/agent-receipt-verify). Run it yourself: npx github:holistis/agent-receipt-verify <url>";

  // Cache for an hour: the underlying data changes per edition, not per minute, and
  // a badge in someone's README should not cost a round trip on every page view.
  res.set("Content-Type", "image/svg+xml; charset=utf-8");
  res.set("Cache-Control", "public, max-age=3600");
  // A literal fallback, not another lookup: with strict index access a second lookup
  // is itself possibly undefined, and a colour is not worth a non-null assertion.
  res.status(200).send(maakSvg(rechts, KLEUREN[label] ?? "#555555", titel));
}

/**
 * A plain JSON twin, for anyone who would rather read the number than show it.
 *
 * Same data, same honesty about what is missing: an endpoint we never measured comes
 * back as measured:false rather than as level 0, because those are different claims.
 */
export function handleBadgeJson(req: Request, res: Response): void {
  const url = typeof req.query.url === "string" ? req.query.url : "";
  const bundel = leesBundel();
  const m = url ? zoekMeting(url, bundel) : null;
  res.set("Cache-Control", "public, max-age=3600");
  res.status(200).json({
    measured: m !== null,
    level: m ? m.trede : null,
    edition: m ? m.editie : null,
    bundleGenerated: bundel.gegenereerd,
    measuredBy: "github.com/holistis/agent-receipt-verify",
    ladder: "https://github.com/holistis/agent-receipt-verify/blob/main/CONFORMANCE.md",
    note: m
      ? "Levels 3 to 5 require a real settlement and are never asserted by this badge."
      : "Not measured. This is not a failing grade: it means no edition has covered this endpoint.",
  });
}
